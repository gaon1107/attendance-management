// 비밀번호 정책 숫자 — **화면과 서버가 함께 보는 단일 출처** (검수 M-3, 2026-08-31).
//
// 🔴 왜 lib/login-policy.ts 가 아니라 별도 파일인가 — 두 가지 제약을 동시에 만족해야 한다.
//    ① **화면(클라이언트 컴포넌트)이 읽어야 한다.** 안내 문구("10자 이상")가 서버 기준과 어긋나면
//       사용자는 화면 말대로 넣었는데 거부당한다. 그런데 `login-policy.ts`는 `@prisma/client`를
//       불러오므로 화면에서 import 하면 브라우저 묶음에 DB 코드가 딸려 들어간다.
//    ② **`scripts/*.mjs`가 `login-policy.ts`를 Node로 직접 불러 쓴다.** 그래서 그 파일에
//       해석 안 되는 import(경로 별칭·확장자 없는 상대경로)를 하나라도 넣으면 스크립트가 즉시 깨진다.
//       → `login-policy.ts`가 이 파일을 import 하는 것도 불가능하다.
//    결론: **아무것도 import 하지 않는 이 파일**을 만들어 양쪽이 각자 읽게 한다.
//
// ⛔ 이 파일에는 **import를 절대 넣지 말 것.** 넣는 순간 화면 묶음이 오염되거나 스크립트가 깨진다.
//    (길이 상한 PASSWORD_MAX_LEN·EMAIL_MAX_LEN은 서버 전용이라 lib/login-policy.ts에 그대로 둔다)

/**
 * 사용자가 **정할 수 있는** 비밀번호의 최소 길이.
 *
 * 🔴 왜 8 → 10인가 (2026-08-31)
 *    H-1(2026-08-30)에서 **계정 잠금이 비밀번호 찍기를 전혀 못 막는다**는 것이 실측으로 확인됐다.
 *    그래서 비밀번호 강도가 사실상 마지막 방어선이 됐다. 8자는 옛 국내 기준의 최소선(10자리)에도 못 미친다.
 *    12자로 더 올리지 않은 이유: 매일 출퇴근을 찍는 사무직 제품이라 부담이 크고,
 *    실제 방어 효과의 대부분은 길이가 아니라 **lib/password-strength.ts(흔한 비밀번호 차단)** 에서 나온다.
 *    (`1234567890`도 `aaaaaaaaaa`도 10자다 — 길이만으로는 절반도 못 막는다)
 *
 * ⚠️ **이 값을 로그인에 쓰면 안 된다.** 로그인은 기존 비밀번호를 받아야 하는데, 여기에 최소 길이를 걸면
 *    **예전에 8~9자로 정한 사람이 전부 못 들어온다**(회사 계정이면 복구 경로가 0이라 회사가 잠긴다).
 *    이 상수는 **비밀번호를 새로 정하는 창구 4곳**에서만 쓴다:
 *    가입(`actions/auth.ts`) · 초대 가입(`actions/invites.ts`) ·
 *    본인 변경(`actions/account.ts`) · 문자 재설정(`actions/password-reset.ts`).
 *
 * ※ 운영자(본사) 계정은 별도로 12자를 요구한다 → 아래 `OPERATOR_PASSWORD_MIN_LEN`. 더 엄격한 쪽이다.
 * ※ 서버가 만드는 임시 비밀번호(`lib/temp-password.ts`, 무작위 10자)는 이 경로를 타지 않는다.
 *    사람이 정하는 값이 아니고 약 57비트라 사람이 만든 12자보다 강하다.
 */
export const PASSWORD_MIN_LEN = 10;

/** 화면 안내 문구에 그대로 쓴다 — 숫자를 화면마다 적지 않게. (예: placeholder, label) */
export const PASSWORD_MIN_HINT = `${PASSWORD_MIN_LEN}자 이상`;

/**
 * 운영자(본사) 계정의 최소 길이 — 고객사보다 **엄하다**.
 *
 * 왜 더 엄한가(검수 M-7, `scripts/create-operator.mjs` 머리말): 고객사 계정은 한 회사만 보고
 * 재설정 창구도 있다. 운영자는 **회사 칸막이를 넘어 전 회원사를 보는 유일한 계정**이고
 * **재설정 창구가 없다.** 세션을 8시간·30분 유휴로 더 짧게 잡은 판단과 같은 이유다.
 *
 * 🔴 **이 숫자를 쓰는 곳은 세 군데뿐이고, 전부 여기만 본다**(2026-11-20에 하나로 모았다):
 *    · `scripts/create-operator.mjs` (서버에서 계정 만들기·비밀번호 재설정)
 *    · `app/actions/operator.ts` (운영자 [내 계정] 비밀번호 변경)
 *    · `app/operator/account/page.tsx` (그 화면의 안내 문구)
 *    ⚠️ 2026-11-20에 [내 계정]을 만들면서 **고객사용 10자를 그대로 가져다 쓴 적이 있다**(검수 치명 1).
 *       화면이 "10자 이상"이라 안내해 오히려 약한 비밀번호를 유도했다. 숫자를 각자 적지 말 것.
 */
export const OPERATOR_PASSWORD_MIN_LEN = 12;
