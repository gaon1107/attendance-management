// 회사 이름을 "사람이 보기에 같은가"로 비교하기 위한 정규화 (2026-11-22, 해지 확인 입력용).
//
// 🔴 **화면과 서버가 반드시 같은 함수를 써야 한다.** 기준이 어긋나면 두 가지 사고가 난다(2026-11-22 재검수 중간 A):
//   · 화면 버튼은 비활성인데 서버는 통과시킬 값 → 운영자가 "왜 안 눌리지?"로 영영 막힌다.
//   · 화면은 허용인데 서버가 거부 → 눌러도 "일치하지 않습니다"만 반복된다.
//  그래서 이 파일 하나만 두고 양쪽이 불러 쓴다. 화면(클라이언트)에서도 쓰므로 서버 전용 코드를 넣지 말 것.
//
// 무엇을 같게 보나
//  · **NFC 정규화** — 맥에서 붙여넣어 저장된 한글(NFD)과 윈도우에서 타이핑한 한글(NFC)은 보이는 모양이 같아도
//    글자 코드가 다르다. 정규화하지 않으면 올바른 이름을 입력해도 영원히 "일치하지 않습니다"가 된다.
//  · **공백 압축** — 이름 중간의 두 칸 공백·줄바꿈·전각 공백(　)은 실수이지 다른 회사가 아니다.
//    (전각 공백도 \s에 포함된다 — 확인함)
//  ⚠️ 대소문자는 **구별한다.** 영문 상호에서 대소문자가 다르면 다른 회사일 수 있고, 여기는 되돌리기 어려운
//     동작(해지)의 마지막 확인 관문이라 느슨하게 만들지 않는다.

/** 비교용으로 다듬은 회사 이름. 빈 문자열이 나올 수 있다(이름이 공백뿐인 경우). */
export function normalizeCompanyName(v: string): string {
  return v.normalize("NFC").replace(/\s+/g, " ").trim();
}

/**
 * 입력한 이름이 그 회사 이름과 "사람이 보기에" 같은가.
 *  🔴 다듬은 회사 이름이 **비어 있으면 항상 false**다 — 이름이 공백뿐인 회사에서 빈 입력으로
 *     해지가 통과하면 안 된다(재검수 경미 2).
 */
export function companyNameMatches(input: string, companyName: string): boolean {
  const wanted = normalizeCompanyName(companyName);
  if (!wanted) return false;
  return normalizeCompanyName(input) === wanted;
}
