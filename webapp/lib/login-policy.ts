/**
 * 실패 횟수를 세는 상한 — **쓰기 부하를 막기 위한 것**이지 정확한 통계를 위한 값이 아니다.
 *  · 왜 필요한가: 잠금을 없앴으므로 실패마다 사용자 행에 쓰기가 발생한다. 상한이 없으면
 *    공격이 지속되는 동안 **끝없이 DB에 쓰게 되고**, SQLite는 쓰기를 한 번에 하나씩만 처리하므로
 *    그 쓰기가 **직원들의 출퇴근 기록과 경합한다**(C-1에서 막으려던 것과 같은 결과).
 *  · 상한에 닿으면 더 쓰지 않는다. 로그인에 성공하면 0으로 되돌아간다.
 *  · ⚠️ **이 상한이 실패 1건당 발생하는 쓰기를 전부 막아 주지는 않는다.** 같은 실패 경로에서
 *    접속기록(AccessEvent) 1행이 따로 쌓이고 그쪽에는 아직 상한이 없다(M-14, 미조치).
 *    "50에서 멈추니 안전하다"고 읽으면 안 된다 — 여기서 막는 것은 **사용자 행 갱신**뿐이다.
 *  · ⚠️ 그래서 이 값은 **신호로 쓰기에 적합하지 않다**(H-1 후속 검수 중간 5):
 *    50은 낮고(IP 하나가 10분에 낼 수 있는 실패량과 같다), 시간이 지나도 저절로 줄지 않으며,
 *    "언제부터 50인가"를 답할 수 없다. 신호가 필요해지면 그때 제대로 설계할 것.
 */
export const FAIL_COUNT_MAX = 50;

