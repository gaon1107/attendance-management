/** 어느 안내서인가 — 관리자 안내서(그림 34장)와 직원 배포용 안내서. */
export type HelpBook = GuideSlug;

/** 도움말을 고르는 키.
 *  🔴 사이드바 강조용 키(NavKey)만으로는 부족하다 — **한 키를 여러 화면이 나눠 쓰기 때문**이다
 *     (예: [근태 현황]과 [정정 승인]이 둘 다 active="records"). 그대로 두면 정정 승인 화면에서
 *     "근태 현황 사용법"이 떴다(검수 중간 1). 그런 화면은 아래 전용 키를 AppShell 의 helpKey 로 넘긴다. */
