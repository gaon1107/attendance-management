//  · 그림까지 있는 자세한 설명이 **고객사 안내서에 있는 화면**은 그 장으로 바로 보낸다(guide).
//    안내서에 없는 화면은 여기 글만 보여 준다 — 그래서 **모든 메뉴가 빠짐없이** 설명된다.
