// ⚠️ 이 파일은 **순수한 글 데이터**다(파일 읽기·DB 조회 없음). 그래야 화면(클라이언트)에서 그대로 쓸 수 있다.
// 🔴 **여기 적은 설명이 실제 화면과 다르면 그게 거짓 안내가 된다.** 화면을 고치면 이 글도 함께 고칠 것.
