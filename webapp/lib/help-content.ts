/** 이 화면에 대한 설명이 있으면 돌려준다. 없으면 null — 그 화면에서는 떠 있는 버튼을 그리지 않는다.
 *  직원이 보면 forEmployee 로 바꿔 끼운다(관리자만 할 수 있는 일을 직원에게 안내하지 않는다). */
export function helpFor(key: HelpKey, role: string): HelpEntry | null {
  const e = HELP[key];
  if (!e) return null;
  if (role === "admin" || !e.forEmployee) return e;
  return { ...e, intro: e.forEmployee.intro ?? e.intro, items: e.forEmployee.items ?? e.items };
}
