-- 홈화면(랜딩) 공개 통계에서 기존 회사를 전부 제외한다.
--
-- 왜 필요한가:
--   바로 앞 마이그레이션(company_is_demo)은 컬럼만 추가하고 기본값이 false다. 그래서 이 보정이 없으면
--   테스트·검증용 회사들이 "가입한 회사 N개사"로 **공개 홈화면에 광고**된다(표시광고법 위험).
--   사장님 로컬에서 손으로 UPDATE 한 번 돌린 상태는 버전관리에 남지 않아, 다른 PC·백업 복원에서
--   그대로 되살아난다(2026-08-09 검수 지적 — 치명).
--
-- 왜 날짜 조건이 없는가:
--   이 마이그레이션이 도는 시점에 이미 Company 표에 있는 행은 **isDemo 개념이 생기기 전에 만들어진
--   회사**다. 즉 "공개 통계에 넣어도 되는지" 아무도 판단하지 않은 회사이므로 전부 제외로 시작한다.
--   · 새 DB       → 행이 없어 아무 일도 일어나지 않는다.
--   · 지금 DB     → 이미 전부 true라 값이 바뀌지 않는다(여러 번 돌려도 안전).
--   · 옛 백업 복원 → 테스트 회사들이 다시 제외된다(이 보정의 목적).
--   ※ 만약 실고객이 이미 있는 DB에 이 마이그레이션이 적용되면 그 회사도 제외된다 —
--     즉 "실수로 광고에 섞이는" 쪽이 아니라 "실수로 안 보이는" 쪽으로 실패한다(안전한 방향).
--     그 경우 해당 회사의 isDemo만 false로 되돌리면 된다.
--
-- 앞으로 테스트 회사를 새로 만들면 기본값이 false(집계 포함)이므로 **직접 true로 바꿔야 한다.**
